export function humanText(text: string): string {
  if (process.env.MAISHU_CLI !== '1' || process.argv.includes('--json')) return text;
  if (Object.hasOwn(exact, text)) return exact[text]!;
  for (const [prefix, translated] of prefixes) if (text.startsWith(prefix)) return translated + text.slice(prefix.length);
  for (const [pattern, render] of patterns) { const match = text.match(pattern); if (match) return render(...match); }
  return text;
}
